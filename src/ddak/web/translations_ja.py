def translate(text: str) -> str:
    """정확 일치와 등록된 전체 문장 패턴만 번역한다."""
    if text in _TEXT:
        return _TEXT[text]
    if match := re.fullmatch(r"변경 파일 ([0-9]+)개를 기록했습니다\.", text):
        return f"変更ファイル{match[1]}件を記録しました。"
    if match := re.fullmatch(r"이미지 ([0-9]+)개의 배포 정보를 기록했습니다\.", text):
        return f"イメージ{match[1]}件のデプロイ情報を記録しました。"
    if match := re.fullmatch(r"검증 기록 ([0-9]+)개", text):
        return f"検証記録{match[1]}件"
    if (
        match := re.fullmatch(
            r"(.+?)[을를] 완료하지 못했습니다\. 원인과 다음 행동을 확인하세요\.", text
        )
    ) and match[1] in _TEXT:
        return f"{_TEXT[match[1]]}を完了できませんでした。原因と次の対応を確認してください。"
    if match := re.fullmatch(r"사용자 시나리오 ([0-9]+)개 중 ([0-9]+)개 통과\.", text):
        return f"ユーザーシナリオ{match[1]}件中{match[2]}件が成功しました。"
    if match := re.fullmatch(r"([\w·.-]+) (이미지 빌드|컨테이너 교체)", text):
        suffix = "イメージのビルド" if match[2] == "이미지 빌드" else "コンテナの置き換え"
        return f"{match[1]}{suffix}"
    if match := re.fullmatch(
        (
            "([\\w·.-]+) 이미지를 (온프레미스 로컬 빌드|클라우드 CodeBuild|기록된 "
            "빌드 환경)에서 만드는 중입니다\\."
        ),
        text,
    ):
        return f"{match[1]}イメージを{_TEXT[match[2]]}でビルドしています。"
    if match := re.fullmatch(r"([\w·.-]+) 이미지를 새로 빌드합니다\.", text):
        return f"{match[1]}イメージを新しくビルドします。"
    if match := re.fullmatch(r"(.+) \(변경 ([0-9]+)\)", text):
        sentence = translate(match[1])
        if sentence != match[1]:
            return f"{sentence} (変更{match[2]}件)"
    if match := re.fullmatch(r"(.+) 이미지 ([a-f0-9]{12})\.", text):
        sentence = translate(match[1])
        if sentence != match[1]:
            return f"{sentence} イメージ {match[2]}。"
    if match := re.fullmatch(
        r"S3 이미지 저장소 (삭제|신규 생성) · (.*?)( \(업로드 이미지 포함\))?", text
    ):
        action = "削除" if match[1] == "삭제" else "新規作成"
        suffix = " (アップロード済み画像を含む)" if match[3] else ""
        return f"S3画像ストレージの{action} · {match[2]}{suffix}"
    if match := re.fullmatch(
        (
            "S3 버킷 (생성|삭제)( 중|을 마쳤습니다|을 완료하지 못했습니다) · (.*?"
            ")( \\(업로드 이미지 포함\\))?"
        ),
        text,
    ):
        action = _TEXT[match[1]]
        state = {
            " 중": "中",
            "을 마쳤습니다": "が完了しました",
            "을 완료하지 못했습니다": "を完了できませんでした",
        }[match[2]]
        suffix = " (アップロード済み画像を含む)" if match[4] else ""
        return f"S3バケットの{action}{state} · {match[3]}{suffix}"
    if match := re.fullmatch(
        (
            "(.+)의 커밋 ([a-f0-9]{1,7}|미확인)를 (온프레미스·클라우드|온프레미스"
            "|클라우드|계획된 환경)에 배포합니다\\. (.+)"
        ),
        text,
    ):
        ending = translate(match[4])
        if ending != match[4]:
            environments = "・".join(_TEXT[env] for env in match[3].split("·"))
            sha = "未確認" if match[2] == "미확인" else match[2]
            ref = "デプロイソース" if match[1] == "배포 소스" else match[1]
            return f"{ref}のコミット{sha}を{environments}にデプロイします。 {ending}"
    if match := re.fullmatch(r"([0-9]+)분(?: ([0-9]+)초)?", text):
        return f"{match[1]}分" + (f"{match[2]}秒" if match[2] else "")
    if match := re.fullmatch(r"([0-9]+(?:\.[0-9]+)?)(개|초|건|행)", text):
        return match[1] + {"개": "件", "초": "秒", "건": "件", "행": "行"}[match[2]]
    if match := re.fullmatch(r"Docker Hub 로그인 확인 불가 — (.+)", text):
        detail = _TEXT.get(match[1], match[1])
        return f"Docker Hubへのログインを確認できません — {detail}"
    if match := re.fullmatch(r"남은 단계 ([0-9]+)개", text):
        return f"残りのステップ{match[1]}件"
    if re.fullmatch(r"(?:관리|읽기|쓰기)(?:·(?:관리|읽기|쓰기))+", text):
        return "・".join(_TEXT[value] for value in text.split("·"))
    return text


# Jinja 표현식은 loader가 따로 처리한다. 전체 템플릿 입력에도 표현식은 보존한다.
_STATIC_TOKENS = re.compile(
    r"({{.*?}}|{%.*?%}|{\#.*?\#}|<!--.*?-->|"
    r"<(script|style|pre|code)\b[^>]*>.*?</\2\s*>|"
    r"<(?:[^<>\"']|\"[^\"]*\"|'[^']*')*>)",
    re.DOTALL | re.IGNORECASE,
)
_DISPLAY_ATTRIBUTE = re.compile(
    r"(?P<prefix>\s(?:title|alt|placeholder|aria-label|aria-description|data-label|data-confirm)"
    r"\s*=\s*)(?P<quote>[\"'])(?P<text>.*?)(?P=quote)",
    re.DOTALL | re.IGNORECASE,
)


def _static_text(text: str) -> str:
    # 공백과 구분 기호는 원형을 유지한다. 단어 부분 치환은 하지 않는다.
    match = re.fullmatch(r"(\s*)(.*?)(\s*)", text, re.DOTALL)
    if not match or not match[2]:
        return text
    core = match[2]
    translated = translate(core)
    if translated == core:
        prefix = re.match(r"[·←—=\[\] :.,]+", core)
        if prefix and translate(core[prefix.end() :]) != core[prefix.end() :]:
            return match[1] + prefix[0] + translate(core[prefix.end() :]) + match[3]
        suffix = re.search(r"[·→ :.,]+$", core)
        if suffix and translate(core[: suffix.start()]) != core[: suffix.start()]:
            return match[1] + translate(core[: suffix.start()]) + suffix[0] + match[3]
        decorated = re.fullmatch(r"([·←—=\[\] :.,]*)(.*?)([·→\[\] :.,]*)", core, re.DOTALL)
        if decorated and decorated[2]:
            translated = decorated[1] + translate(decorated[2]) + decorated[3]
    return match[1] + translated + match[3]


def translate_static(text: str) -> str:
    """정적 HTML 표시 문구를 번역하고 태그·데이터 속성·Jinja·코드를 보존한다.

    Jinja 구분자 밖 조각도 허용한다. 동적 값은 이 함수에 전달하지 않는다.
    """
    output = []
    position = 0
    for match in _STATIC_TOKENS.finditer(text):
        output.append(_static_fragment(text[position : match.start()]))
        token = match[0]
        if token.startswith("<") and not match[2] and not token.startswith("<!--"):
            token = _DISPLAY_ATTRIBUTE.sub(
                lambda attr: (
                    attr["prefix"] + attr["quote"] + _static_text(attr["text"]) + attr["quote"]
                ),
                token,
            )
        output.append(token)
        position = match.end()
    output.append(_static_fragment(text[position:]))
    return "".join(output)


def _static_fragment(text: str) -> str:
    # Jinja 출력 바로 뒤에는 열린 태그의 끝(예: '">')이 남을 수 있다.
    if ">" in text and "<" not in text.split(">", 1)[0]:
        head, separator, tail = text.partition(">")
        # progress의 aria-label="{{ target(track) }} 작업 처리" 조각.
        # 앞 속성 이름을 모르는 조각은 일반 치환하지 않는다.
        if re.fullmatch(r" 작업 처리[\"']", head):
            head = " 処理済み" + head[-1]
        return head + separator + _static_text(tail)
    # 조각 끝에 Jinja 값 직전의 열린 태그가 있으면 텍스트 부분만 번역한다.
    if "<" in text:
        head, separator, tail = text.partition("<")
        return _static_text(head) + separator + tail
    return _static_text(text)
